from sqlmodel import Session, select

from app.db.session import engine
from app.models import Page


ABOUT_CONTENT = """
## Кто мы

Школьный парламент Зыковской СОШ — это орган ученического самоуправления.
Мы представляем интересы учеников, организуем мероприятия и помогаем
делать школьную жизнь интереснее.

## Чем занимаемся

- Организуем школьные мероприятия: концерты, конкурсы, спортивные турниры
- Представляем интересы учеников перед администрацией школы
- Ведём информационную работу: новости, объявления
- Помогаем в решении школьных вопросов

## Как устроены

Парламент состоит из председателя, заместителя, секретаря и комитетов
по разным направлениям: учебный, спортивный, медиа, культурный.

## Когда создан

Парламент был создан в 2024 году. За это время мы провели более 20
мероприятий, среди которых — школьные олимпиады, дни самоуправления,
спортивные турниры и тематические недели.

## Как попасть

Если ты хочешь присоединиться к парламенту — приходи на наши собрания
или напиши нам через раздел «Обратная связь». Мы всегда рады новым идеям.
"""


def seed_pages():
    """Создаёт начальные страницы, если их нет."""
    with Session(engine) as session:
        existing = session.exec(select(Page).where(Page.slug == "about")).first()
        if existing:
            print("Страница 'about' уже существует, пропускаем")
            return

        page = Page(
            slug="about",
            title="О парламенте",
            content_md=ABOUT_CONTENT.strip(),
        )
        session.add(page)
        session.commit()
        print(f"Создана страница: {page.slug} — {page.title}")


if __name__ == "__main__":
    seed_pages()